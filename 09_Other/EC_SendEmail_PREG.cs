public class EC_SendEmail_PREG : CustomFunctionBase
{
public object Eval(object ThisObject)
{
ActionFunctionParams afp = (ActionFunctionParams)ThisObject;
DataPoint dpAction = afp.ActionDataPoint;
Subject subj = dpAction.Record.Subject;

string siteNumber = subj.StudySite.Site.Number;
string subjName = subj.Name;
string country = subj.StudySite.Site.Country;

const string from = "Pregnancy_Alert@mdsol.com";
string to = (string)CustomFunction.PerformCustomFunction("CF_Email_Recipients", dpAction.Field.CRFVersion.ID, new object[] { subj.StudySite.Study.Environment, "All" });
string topic = "[" + subj.StudySite.Study.Environment.ToUpper() + "] " + "**Pregnancy Alert** (Study " + subj.StudySite.Study.Name + " / Country " + country.ToString() + " / Site " + siteNumber + " / Patient " + subjName + ")";
StringBuilder body = new StringBuilder("");
if (dpAction.Active && dpAction.IsObjectChanged && dpAction.Data == "POSITIVE")
{
    body.Append(Environment.NewLine + Environment.NewLine+"Pregnancy test Reported as Positive" + Environment.NewLine + "Study: CRN00808-12");
    body.Append(Environment.NewLine + "Country: " + dpAction.Record.Subject.StudySite.Site.Country.ToString());
    body.Append(Environment.NewLine + "Site number: " + dpAction.Record.Subject.StudySite.Site.Number);
    body.Append(Environment.NewLine + "Subject number: " + dpAction.Record.Subject.Name);
    body.Append(Environment.NewLine + "Visit Name: " + dpAction.Record.Instance.Name);
    body.Append(Environment.NewLine + Environment.NewLine +"*** This message was generated by an automated system, please DO NOT reply to this message. ***");
    Message.SendEmail(to, from, topic, body.ToString());
}
return null;
}
}

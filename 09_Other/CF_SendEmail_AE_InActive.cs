public class CF_SendEmail_AE_InActive : CustomFunctionBase
{
public object Eval(object ThisObject)
{
ActionFunctionParams afp = (ActionFunctionParams)ThisObject;
    DataPoint dpAction = afp.ActionDataPoint;
    Subject subject = dpAction.Record.Subject;
    string siteNumber = subject.StudySite.StudySiteNumber;
    string subjName = subject.Name;
    string country = subject.StudySite.Site.Country;

    const string from = "SAE_Alert@mdsol.com";
    string to = (string)CustomFunction.PerformCustomFunction("CF_Aid_GetTo", dpAction.Field.CRFVersion.ID, new object[] { subject.StudySite.Study.Environment.ToUpper() });
    string topic = "[" + subject.StudySite.Study.Environment.ToUpper() + "] SAE Log Line Inactived Alert "+ subject.StudySite.Study.Name + " / Country " + country.ToString() + " / Site " + siteNumber + " / Patient " + subjName + ")";
    StringBuilder body = new StringBuilder("");

    DataPage CurentPG = dpAction.Record.DataPage;
    Records allRCs = CurentPG.Records;
    bool dobreak = false;
    foreach (Record RC in allRCs)
    {
        if (RC == null || RC.RecordPosition == 0) continue;
        foreach (DataPoint dp in RC.DataPoints)
        {
            if (dp == null) continue;
            if (dp.IsObjectChanged && !dp.Active)
            {
                if(dp.Field.OID== "AESER"&&dp.Data=="Y")
                {
                    body = BodyCreat(dp, body, subject);
                    Message.SendEmail(to, from, topic, body.ToString());
                    dobreak = true;
                    break;
                }
            }
        }
        if (dobreak) break;
    }
    return null;
}
StringBuilder BodyCreat(DataPoint dp, StringBuilder body, Subject subj)
{
    body.Append("Study: " + subj.StudySite.Study.Name);
    body.Append("\n" + "Country: " + subj.StudySite.Site.Country.ToString());
    body.Append("\n" + "Site number: " + subj.StudySite.StudySiteNumber);
    body.Append("\n" + "Subject number: " + dp.Record.Subject.Name);
    body.Append("\n" + "Inactived AE Log Line Number: " + dp.Record.RecordPosition);
    body.Append("\n" + "AE Term: " + dp.Record.DataPoints.FindByFieldOID("AETERM").UserValue());
    body.Append("\n" + "AE Start Date: " + dp.Record.DataPoints.FindByFieldOID("AESTDAT").UserValue());
    body.Append("\n" + "AE Log Line Inactived By: " + dp.Interaction.TrueUser.FullName);
    body.Append("\n" + " " + "\n" + "*** This message was generated by an automated system, please DO NOT reply to this message. ***" + "\n" + "\n" + "Note: This does not require a query to fire to the site - only an email to the address with the study name, subject country, site number, subject number, AE log line number, AE term, AE start date, name of individual who created/updated SAE information.");
    return body;
}
}

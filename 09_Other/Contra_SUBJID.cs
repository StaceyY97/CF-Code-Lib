public class Contra_SUBJID : CustomFunctionBase
{
public object Eval(object ThisObject)
{
// Checks for Unique Subject ID within a site


        DataPoint currentSubject_DP=(DataPoint) ThisObject;

        bool isDuplicate=false;

        if(currentSubject_DP.Data!=string.Empty)

        {

            string[] allSubjectValues=currentSubject_DP.Record.Subject.StudySite.GetAllValuesForOIDPath(

null, currentSubject_DP.Field.Form.OID,

currentSubject_DP.Field.OID, new int[] { currentSubject_DP.Record.Subject.ID } );

            for(int i=0; i<allSubjectValues.Length && !isDuplicate; i++)

            {

                if(allSubjectValues[i]==currentSubject_DP.Data) isDuplicate=true;

            }

        }

        return isDuplicate;
}
}
